"""Generate words.js and puzzles.js.

5-letter (main mode): Wordle answer list = common, Wordle allowed list = accepted guesses.
4-letter (easy mode): top-N subtitle-frequency words that are in the macOS dictionary = common,
all lowercase 4-letter dictionary words = accepted guesses.
A puzzle is scheduled only if it has at least one all-common-word solution.
"""
import json, random, datetime, os, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..') + '/'
SRC = {
    'answers.txt': 'https://gist.githubusercontent.com/cfreshman/a03ef2cba789d8cf00c08f767e0fad7b/raw/wordle-answers-alphabetical.txt',
    'allowed.txt': 'https://gist.githubusercontent.com/cfreshman/cdcdf777450c5b5301e439061d29694c/raw/wordle-allowed-guesses.txt',
    'en_50k.txt':  'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt',
    'google10k.txt': 'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-no-swears.txt',
}
for name, url in SRC.items():
    p = os.path.join(HERE, name)
    if not os.path.exists(p):
        urllib.request.urlretrieve(url, p)
def lines(name): return [l.split()[0] for l in open(os.path.join(HERE, name)) if l.strip()]

EPOCH = datetime.date(2026, 9, 4)
